import json
import re
from typing import Dict, Any, List, Optional
from sqlalchemy.orm import Session

from backend.core.config import settings
from backend.schemas.triggers import normalize_trigger_word
from backend.services.trigger_generator import TriggerGeneratorService


class SummarizationService:
    """
    AI Summarization & Context Extraction Service:
    Extracts structured context (trigger, title, summary, decisions, next steps)
    from pasted conversation logs or raw text notes.
    """

    @classmethod
    def extract_context_from_text(
        cls,
        raw_text: str,
        db: Optional[Session] = None,
        user_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Extract structured context and auto-generate trigger word.
        Uses Gemini if GEMINI_API_KEY is configured; falls back cleanly to heuristic parser.
        """
        if not raw_text or not raw_text.strip():
            return cls._empty_draft()

        # Step 1: Generate high quality trigger words
        trigger_meta = TriggerGeneratorService.generate_triggers_from_chat(
            chat_text=raw_text,
            db=db,
            user_id=user_id,
        )

        # Step 2: Extract structured context
        if settings.gemini_available:
            try:
                result = cls._extract_with_gemini(raw_text)
                # Ensure trigger metadata from generator is merged if not present
                if not result.get("suggested_trigger"):
                    result["suggested_trigger"] = trigger_meta["primary_trigger"]
                result["alternative_triggers"] = trigger_meta.get("alternative_triggers", [])
                result["trigger_reasoning"] = trigger_meta.get("reasoning", "")
                result["trigger_candidates"] = trigger_meta.get("candidates", [])
                return result
            except Exception as e:
                # Fallback to rule-based parser on any API failure
                result = cls._extract_heuristic(raw_text, trigger_meta)
                result["_ai_note"] = f"Gemini API call encountered an error: {str(e)}. Used heuristic parser."
                return result

        result = cls._extract_heuristic(raw_text, trigger_meta)
        result["_ai_note"] = "Extracted using offline NLP engine (Configure GEMINI_API_KEY in .env for advanced AI extraction)."
        return result

    @classmethod
    def _extract_with_gemini(cls, raw_text: str) -> Dict[str, Any]:
        """Extract structured context using Google Gemini API."""
        from google import genai
        client = genai.Client(api_key=settings.GEMINI_API_KEY)

        prompt = f"""
You are an expert context analyzer for Context Bank.
Analyze the following conversation or notes and extract a structured project context.
Return ONLY valid JSON matching this schema:
{{
  "suggested_trigger": "A concise uppercase trigger word (e.g. VOXCENT, SQLPATH, RESUME)",
  "title": "A clear, descriptive title",
  "summary": "A concise 2-4 sentence summary of what this is, its architecture, and current state",
  "category": "One category: Projects, Learning, Career, Specs, or General",
  "tags": ["tag1", "tag2"],
  "status": "Active or In Progress or Completed",
  "confirmed_decisions": ["confirmed decision 1", "confirmed decision 2"],
  "proposed_changes": ["proposed change 1"],
  "completed_work": ["completed task 1", "completed task 2"],
  "open_questions": ["unresolved question 1"],
  "next_steps": ["immediate next step 1", "next step 2"]
}}

Source text:
{raw_text[:12000]}
"""
        response = client.models.generate_content(
            model=settings.GEMINI_MODEL,
            contents=prompt,
        )

        resp_text = response.text or ""
        # Strip potential markdown json code block
        match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", resp_text)
        json_str = match.group(1) if match else resp_text

        data = json.loads(json_str)

        # Normalize suggested trigger
        raw_trig = data.get("suggested_trigger", "PROJECT")
        try:
            data["suggested_trigger"] = normalize_trigger_word(raw_trig)
        except Exception:
            data["suggested_trigger"] = "MYCONTEXT"

        data["_ai_note"] = f"Generated by {settings.GEMINI_MODEL}"
        return data

    @classmethod
    def _extract_heuristic(cls, raw_text: str, trigger_meta: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Offline rule-based context extraction."""
        lines = [line.strip() for line in raw_text.splitlines() if line.strip()]

        # Determine trigger from trigger_meta or default
        if trigger_meta and trigger_meta.get("primary_trigger"):
            suggested_trig = trigger_meta["primary_trigger"]
            alt_triggers = trigger_meta.get("alternative_triggers", [])
            trigger_reason = trigger_meta.get("reasoning", "")
            candidates = trigger_meta.get("candidates", [])
        else:
            suggested_trig = "CONTEXT"
            alt_triggers = []
            trigger_reason = "Default heuristic"
            candidates = ["CONTEXT"]

        # Guess title
        title = lines[0] if lines else f"{suggested_trig.title()} Context"
        if title.startswith("#"):
            title = title.lstrip("#").strip()
        if len(title) > 80:
            title = title[:80] + "..."

        summary = "\n".join(lines[1:5]) if len(lines) > 1 else raw_text[:300]
        if not summary.strip():
            summary = title

        # Search for decisions, completed items, next steps
        confirmed_decisions = []
        completed_work = []
        open_questions = []
        next_steps = []

        for line in lines:
            line_clean = line.lstrip("-*# >").strip()
            lower = line_clean.lower()
            if any(k in lower for k in ["decided", "decision:", "architecture:"]):
                confirmed_decisions.append(line_clean)
            elif any(k in lower for k in ["completed", "done", "[x]", "finished"]):
                completed_work.append(line_clean)
            elif any(k in lower for k in ["?", "question:", "todo: clarify", "unresolved"]):
                open_questions.append(line_clean)
            elif any(k in lower for k in ["next step", "next:", "todo:", "[ ]"]):
                next_steps.append(line_clean)

        return {
            "suggested_trigger": suggested_trig,
            "alternative_triggers": alt_triggers,
            "trigger_reasoning": trigger_reason,
            "trigger_candidates": candidates,
            "title": title,
            "summary": summary,
            "category": "Projects",
            "tags": ["auto-chat", "extracted"],
            "status": "In Progress",
            "confirmed_decisions": confirmed_decisions or ["Project requirements specified in chat."],
            "proposed_changes": [],
            "completed_work": completed_work or ["Draft gathered from conversation."],
            "open_questions": open_questions,
            "next_steps": next_steps or ["Review and refine extracted context details."],
        }

    @staticmethod
    def _empty_draft() -> Dict[str, Any]:
        return {
            "suggested_trigger": "",
            "title": "",
            "summary": "",
            "category": "General",
            "tags": [],
            "status": "Active",
            "confirmed_decisions": [],
            "proposed_changes": [],
            "completed_work": [],
            "open_questions": [],
            "next_steps": [],
        }
